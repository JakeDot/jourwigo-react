import React, { useState } from 'react';
import { BranchingDialogConfig, DialogFrame, QuestionType } from '../types/wherigo';
import { MessageSquare, ArrowRight, Plus, Trash2, Code, Copy, Check, Sparkles } from 'lucide-react';

interface DialogBuilderViewProps {
  onAddDialogToCartridge: (dialogName: string, luaCode: string) => void;
}

export const DialogBuilderView: React.FC<DialogBuilderViewProps> = ({ onAddDialogToCartridge }) => {
  const [config, setConfig] = useState<BranchingDialogConfig>({
    sequenceName: 'dialogBranchingDemo',
    initialFrames: [
      { id: '1', text: 'Welcome traveler! You have arrived at the mystical ancient ruins.', mediaVar: 'mediaIntro' },
      { id: '2', text: 'Legend speaks of a hidden treasure buried beneath these stones.', mediaVar: 'mediaRuins' },
      { id: '3', text: 'Beware, for ancient guardians still watch over this sanctuary.', mediaVar: 'mediaGuardian' },
    ],
    question: {
      text: 'Do you wish to enter the ruins and search for the treasure?',
      mediaVar: 'mediaQuestion',
      type: 'YES_NO',
      choices: ['Yes', 'No'],
      resultVariable: 'varRuinsAccepted',
    },
    branches: [
      { choice: 'Yes', followUpText: 'You step bravely into the shadows of the ruin...', mediaVar: 'mediaEnter' },
      { choice: 'No', followUpText: 'You decide to stay safe and turn back.', mediaVar: 'mediaTurnBack' },
    ],
    recording: {
      enabled: true,
      type: 'SNAP_PHOTO',
      text: 'Take a photo of the ancient rune symbol to unlock the portal',
      resultMediaVar: 'mediaPhotoProof',
    },
    mergedTarget: {
      text: 'Regardless of choice, your journey continues onward to the ancient town square.',
      mediaVar: 'mediaTown',
    },
  });

  const [copied, setCopied] = useState(false);

  // Generate Lua code for the dialogue graph
  const generateLuaCode = (): string => {
    let sb = `${config.sequenceName} = function()\n`;
    sb += `    -- Branching and merging dialogue generated by jourwigo DialogBuilder\n`;

    const totalSteps = config.initialFrames.length + 1 + config.branches.length + (config.recording?.enabled ? 1 : 0) + 1;
    const stepNames = Array.from({ length: totalSteps }, (_, i) => `step_${i + 1}`).join(', ');
    sb += `    local ${stepNames}\n\n`;

    let stepIdx = 1;

    // Initial frames
    config.initialFrames.forEach((frame) => {
      const nextStep = `step_${stepIdx + 1}`;
      const mediaPart = frame.mediaVar ? `, Media = ${frame.mediaVar}` : '';
      sb += `    step_${stepIdx} = function()\n`;
      sb += `        Wherigo.MessageBox({ Text = "${frame.text.replace(/"/g, '\\"')}"${mediaPart}, Callback = function() ${nextStep}() end })\n`;
      sb += `    end\n\n`;
      stepIdx++;
    });

    // Question step
    const questionStepIdx = stepIdx;
    const questionMedia = config.question.mediaVar ? `, Media = ${config.question.mediaVar}` : '';
    const choicesArr = config.question.choices.map((c) => `"${c.replace(/"/g, '\\"')}"`).join(', ');

    sb += `    step_${questionStepIdx} = function()\n`;
    sb += `        Wherigo.MessageBox({\n`;
    sb += `            Text = "${config.question.text.replace(/"/g, '\\"')}"${questionMedia},\n`;
    sb += `            Buttons = {${choicesArr}},\n`;
    sb += `            Callback = function(action)\n`;

    const mergeStepIdx = totalSteps;
    const branchStartIdx = questionStepIdx + 1;

    config.branches.forEach((b, idx) => {
      const bStep = `step_${branchStartIdx + idx}`;
      const cond = idx === 0 ? `if action == "Button1" then` : `elseif action == "Button${idx + 1}" then`;
      sb += `                ${cond}\n`;
      sb += `                    ${config.question.resultVariable} = "${b.choice}"\n`;
      sb += `                    ${bStep}()\n`;
    });
    sb += `                else\n`;
    sb += `                    step_${mergeStepIdx}()\n`;
    sb += `                end\n`;
    sb += `            end\n`;
    sb += `        })\n`;
    sb += `    end\n\n`;
    stepIdx++;

    // Branch steps
    config.branches.forEach((b) => {
      const mediaPart = b.mediaVar ? `, Media = ${b.mediaVar}` : '';
      const nextStepTarget = config.recording?.enabled ? `step_${mergeStepIdx - 1}` : `step_${mergeStepIdx}`;
      sb += `    step_${stepIdx} = function()\n`;
      sb += `        Wherigo.MessageBox({ Text = "${b.followUpText.replace(/"/g, '\\"')}"${mediaPart}, Callback = function() ${nextStepTarget}() end })\n`;
      sb += `    end\n\n`;
      stepIdx++;
    });

    // Recording step (if enabled)
    if (config.recording?.enabled) {
      sb += `    step_${stepIdx} = function()\n`;
      sb += `        -- MediaPicker Extension: ${config.recording.type}\n`;
      sb += `        Wherigo.MessageBox({\n`;
      sb += `            Text = "${config.recording.text.replace(/"/g, '\\"')}",\n`;
      sb += `            Callback = function()\n`;
      sb += `                ${config.recording.resultMediaVar} = Wherigo.SnapPhoto()\n`;
      sb += `                step_${mergeStepIdx}()\n`;
      sb += `            end\n`;
      sb += `        })\n`;
      sb += `    end\n\n`;
      stepIdx++;
    }

    // Merged step
    const mergeMedia = config.mergedTarget.mediaVar ? `, Media = ${config.mergedTarget.mediaVar}` : '';
    sb += `    step_${mergeStepIdx} = function()\n`;
    sb += `        Wherigo.MessageBox({ Text = "${config.mergedTarget.text.replace(/"/g, '\\"')}"${mergeMedia} })\n`;
    sb += `    end\n\n`;

    // Start execution
    sb += `    step_1()\n`;
    sb += `end\n`;

    return sb;
  };

  const handleAddFrame = () => {
    const num = config.initialFrames.length + 1;
    setConfig({
      ...config,
      initialFrames: [
        ...config.initialFrames,
        { id: String(Date.now()), text: `Frame ${num} narration text...`, mediaVar: `mediaFrame${num}` },
      ],
    });
  };

  const handleRemoveFrame = (id: string) => {
    setConfig({
      ...config,
      initialFrames: config.initialFrames.filter((f) => f.id !== id),
    });
  };

  const handleCopyCode = () => {
    navigator.clipboard.writeText(generateLuaCode());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="space-y-6">
      {/* Header card */}
      <div className="bg-white rounded-lg border border-slate-200 p-5 shadow-xs">
        <div className="flex flex-wrap items-center justify-between gap-3 mb-4">
          <div className="flex items-center gap-2">
            <MessageSquare className="w-5 h-5 text-blue-600" />
            <div>
              <h2 className="text-base font-bold text-slate-800">Visual Dialogue Graph &amp; Story Flow</h2>
              <p className="text-xs text-slate-500">
                Design non-linear dialogue trees with multiple narrative frames, decision questions, branch paths, and convergence.
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopyCode}
              className="px-3 py-1.5 text-xs font-medium rounded-md border border-slate-300 bg-white hover:bg-slate-50 text-slate-700 flex items-center gap-1.5 transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
              {copied ? 'Copied!' : 'Copy Lua'}
            </button>
            <button
              onClick={() => onAddDialogToCartridge(config.sequenceName, generateLuaCode())}
              className="px-3.5 py-1.5 text-xs font-semibold rounded-md bg-blue-600 hover:bg-blue-700 text-white flex items-center gap-1.5 transition-colors shadow-xs"
            >
              <Sparkles className="w-3.5 h-3.5" />
              Add Dialog to Cartridge
            </button>
          </div>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          <div>
            <label className="block text-xs font-semibold text-slate-600 mb-1">
              Dialogue Sequence Name (Function)
            </label>
            <input
              type="text"
              value={config.sequenceName}
              onChange={(e) => setConfig({ ...config, sequenceName: e.target.value })}
              className="w-full text-sm font-mono px-3 py-1.5 border border-slate-300 rounded-md focus:border-blue-500 outline-none"
            />
          </div>

          <div>
            <label className="block text-xs font-semibold text-slate-600 mb-1">
              Save Result to Global Variable
            </label>
            <input
              type="text"
              value={config.question.resultVariable}
              onChange={(e) =>
                setConfig({
                  ...config,
                  question: { ...config.question, resultVariable: e.target.value },
                })
              }
              className="w-full text-sm font-mono px-3 py-1.5 border border-slate-300 rounded-md focus:border-blue-500 outline-none"
            />
          </div>
        </div>
      </div>

      {/* Interactive Visual Graph Flow (Left-to-Right) */}
      <div className="bg-white rounded-lg border border-slate-200 p-5 shadow-xs">
        <h3 className="text-sm font-bold text-slate-800 mb-1">Visual Graph Flow (Branching &amp; Merging Diagram)</h3>
        <p className="text-xs text-slate-500 mb-4">
          The flow progresses through initial frames, branches on player decisions, handles media recording, and rejoins at the merged target node.
        </p>

        <div className="flex flex-row items-stretch gap-3 overflow-x-auto p-4 bg-slate-50/80 rounded-lg border border-slate-200 min-h-[300px]">
          {/* Column 1: Initial Narrative Frames */}
          <div className="flex flex-col gap-3 min-w-[240px] max-w-[260px] shrink-0">
            <div className="flex items-center justify-between">
              <span className="text-xs font-bold text-slate-700">1. Initial Frames ({config.initialFrames.length})</span>
              <button
                type="button"
                onClick={handleAddFrame}
                className="text-[11px] text-blue-600 hover:text-blue-800 font-semibold flex items-center gap-0.5"
              >
                <Plus className="w-3 h-3" /> Add
              </button>
            </div>

            {config.initialFrames.map((f, idx) => (
              <div
                key={f.id}
                className="bg-white rounded-md p-3 border border-slate-200 border-l-4 border-l-blue-600 shadow-xs relative group"
              >
                <div className="flex items-center justify-between mb-1">
                  <span className="text-[11px] font-bold text-slate-700">Frame {idx + 1}</span>
                  <div className="flex items-center gap-1">
                    <span className="px-1.5 py-0.5 rounded text-[10px] bg-blue-50 text-blue-700 font-semibold">
                      Normal
                    </span>
                    {config.initialFrames.length > 1 && (
                      <button
                        onClick={() => handleRemoveFrame(f.id)}
                        className="text-slate-400 hover:text-red-600 p-0.5"
                      >
                        <Trash2 className="w-3 h-3" />
                      </button>
                    )}
                  </div>
                </div>
                <textarea
                  rows={2}
                  value={f.text}
                  onChange={(e) => {
                    const copy = [...config.initialFrames];
                    copy[idx].text = e.target.value;
                    setConfig({ ...config, initialFrames: copy });
                  }}
                  className="w-full text-xs text-slate-800 border border-slate-200 rounded p-1.5 focus:border-blue-400 outline-none"
                />
                <input
                  type="text"
                  placeholder="Media var"
                  value={f.mediaVar || ''}
                  onChange={(e) => {
                    const copy = [...config.initialFrames];
                    copy[idx].mediaVar = e.target.value;
                    setConfig({ ...config, initialFrames: copy });
                  }}
                  className="w-full text-[10px] font-mono text-blue-700 bg-blue-50/50 border border-blue-200 rounded px-1.5 py-0.5 mt-1"
                />
              </div>
            ))}
          </div>

          <div className="flex items-center justify-center text-slate-400 shrink-0 select-none">
            <ArrowRight className="w-6 h-6" />
          </div>

          {/* Column 2: Decision Question Node */}
          <div className="flex flex-col gap-3 min-w-[240px] max-w-[260px] shrink-0 justify-center">
            <span className="text-xs font-bold text-amber-800">2. Decision Question</span>

            <div className="bg-amber-50/70 rounded-md p-3.5 border border-amber-300 border-l-4 border-l-amber-500 shadow-xs">
              <div className="flex items-center justify-between mb-1.5">
                <span className="text-xs font-bold text-amber-900">Question Node</span>
                <span className="px-1.5 py-0.5 rounded text-[10px] bg-amber-200 text-amber-900 font-bold">
                  {config.question.type}
                </span>
              </div>

              <textarea
                rows={3}
                value={config.question.text}
                onChange={(e) =>
                  setConfig({
                    ...config,
                    question: { ...config.question, text: e.target.value },
                  })
                }
                className="w-full text-xs text-slate-800 border border-amber-200 rounded p-1.5 bg-white focus:border-amber-400 outline-none"
              />

              <div className="mt-2 space-y-1.5">
                <input
                  type="text"
                  placeholder="Media var"
                  value={config.question.mediaVar}
                  onChange={(e) =>
                    setConfig({
                      ...config,
                      question: { ...config.question, mediaVar: e.target.value },
                    })
                  }
                  className="w-full text-[10px] font-mono text-amber-800 bg-amber-100/50 border border-amber-200 rounded px-1.5 py-0.5"
                />

                <div className="text-[11px] font-medium text-amber-800 pt-1">
                  Choices: {config.question.choices.join(', ')}
                </div>
              </div>
            </div>
          </div>

          <div className="flex items-center justify-center text-slate-400 shrink-0 select-none">
            <ArrowRight className="w-6 h-6" />
          </div>

          {/* Column 3: Choice Branch Nodes */}
          <div className="flex flex-col gap-3 min-w-[240px] max-w-[260px] shrink-0 justify-center">
            <span className="text-xs font-bold text-emerald-800">3. Choice Branches ({config.branches.length})</span>

            {config.branches.map((b, idx) => (
              <div
                key={idx}
                className={`bg-white rounded-md p-3 border border-slate-200 border-l-4 shadow-xs ${
                  idx === 0 ? 'border-l-emerald-600' : 'border-l-rose-500'
                }`}
              >
                <div className="flex items-center justify-between mb-1">
                  <span className="text-xs font-bold text-slate-800">Branch '{b.choice}'</span>
                  <span
                    className={`px-1.5 py-0.5 rounded text-[10px] font-bold ${
                      idx === 0 ? 'bg-emerald-100 text-emerald-800' : 'bg-rose-100 text-rose-800'
                    }`}
                  >
                    Choice {idx + 1}
                  </span>
                </div>

                <textarea
                  rows={2}
                  value={b.followUpText}
                  onChange={(e) => {
                    const copy = [...config.branches];
                    copy[idx].followUpText = e.target.value;
                    setConfig({ ...config, branches: copy });
                  }}
                  className="w-full text-xs text-slate-800 border border-slate-200 rounded p-1.5 focus:border-emerald-400 outline-none"
                />

                <input
                  type="text"
                  placeholder="Media var"
                  value={b.mediaVar || ''}
                  onChange={(e) => {
                    const copy = [...config.branches];
                    copy[idx].mediaVar = e.target.value;
                    setConfig({ ...config, branches: copy });
                  }}
                  className="w-full text-[10px] font-mono text-emerald-700 bg-emerald-50/50 border border-emerald-200 rounded px-1.5 py-0.5 mt-1"
                />

                <div className="text-[10px] text-slate-400 mt-1">➔ Converges into Next Node</div>
              </div>
            ))}
          </div>

          <div className="flex items-center justify-center text-slate-400 shrink-0 select-none">
            <ArrowRight className="w-6 h-6" />
          </div>

          {/* Column 4: Recording Node & Merged Target Destination */}
          <div className="flex flex-col gap-3 min-w-[240px] max-w-[260px] shrink-0 justify-center">
            <span className="text-xs font-bold text-purple-800">4. Recording &amp; Merged Target</span>

            {/* Optional MediaPicker Recording Card */}
            {config.recording?.enabled && (
              <div className="bg-teal-50/80 rounded-md p-3 border border-teal-200 border-l-4 border-l-teal-600 shadow-xs">
                <div className="flex items-center justify-between mb-1">
                  <span className="text-xs font-bold text-teal-900">MediaPicker Node</span>
                  <span className="px-1.5 py-0.5 rounded text-[10px] bg-teal-200 text-teal-900 font-bold">
                    {config.recording.type}
                  </span>
                </div>
                <p className="text-xs text-teal-950 mb-1">📷 {config.recording.text}</p>
                <div className="text-[10px] font-mono text-teal-700">
                  Result: {config.recording.resultMediaVar}
                </div>
              </div>
            )}

            {/* Merged Destination Node */}
            <div className="bg-purple-50/80 rounded-md p-3 border border-purple-200 border-l-4 border-l-purple-600 shadow-xs">
              <div className="flex items-center justify-between mb-1">
                <span className="text-xs font-bold text-purple-900">Merged Target Node</span>
                <span className="px-1.5 py-0.5 rounded text-[10px] bg-purple-200 text-purple-900 font-bold">
                  Convergence
                </span>
              </div>
              <textarea
                rows={3}
                value={config.mergedTarget.text}
                onChange={(e) =>
                  setConfig({
                    ...config,
                    mergedTarget: { ...config.mergedTarget, text: e.target.value },
                  })
                }
                className="w-full text-xs text-slate-800 border border-purple-200 rounded p-1.5 bg-white focus:border-purple-400 outline-none"
              />
              <input
                type="text"
                placeholder="Media var"
                value={config.mergedTarget.mediaVar}
                onChange={(e) =>
                  setConfig({
                    ...config,
                    mergedTarget: { ...config.mergedTarget, mediaVar: e.target.value },
                  })
                }
                className="w-full text-[10px] font-mono text-purple-800 bg-purple-100/50 border border-purple-200 rounded px-1.5 py-0.5 mt-1"
              />
            </div>
          </div>
        </div>
      </div>

      {/* Generated Dialogue Code Preview */}
      <div className="bg-white rounded-lg border border-slate-200 p-5 shadow-xs">
        <div className="flex items-center justify-between mb-2">
          <div className="flex items-center gap-1.5">
            <Code className="w-4 h-4 text-blue-600" />
            <h3 className="text-xs font-bold text-slate-700">Generated Wherigo Dialogue Lua Code</h3>
          </div>
        </div>
        <pre className="p-3 bg-slate-900 text-slate-100 rounded-lg text-xs font-mono overflow-x-auto max-h-72">
          {generateLuaCode()}
        </pre>
      </div>
    </div>
  );
};
