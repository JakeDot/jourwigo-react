import { Cartridge, WherigoObject, PropertyType } from '../types/wherigo';

export function escapeLua(value: string | undefined): string {
  if (!value) return '';
  return String(value)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r\n/g, '\\n')
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '\\n');
}

export function formatPropertyValue(val: string, type: PropertyType): string {
  if (type === 'NUMBER') {
    const num = parseFloat(val);
    return isNaN(num) ? '0' : num.toString();
  }
  if (type === 'BOOLEAN') {
    const str = String(val).trim().toLowerCase();
    return str === 'true' || str === '1' || str === 'yes' ? 'true' : 'false';
  }
  if (type === 'EXPRESSION') {
    return val ? val.trim() : 'nil';
  }
  // STRING
  return `"${escapeLua(val)}"`;
}

/**
 * Topologically sort objects so that containers / parents are declared before children
 */
export function getSortedObjects(objects: WherigoObject[]): WherigoObject[] {
  const sorted: WherigoObject[] = [];
  const visited = new Set<string>();

  function visit(obj: WherigoObject | undefined) {
    if (!obj || visited.has(obj.id)) return;
    if (obj.parentId) {
      const parent = objects.find((o) => o.id === obj.parentId);
      if (parent) visit(parent);
    }
    visited.add(obj.id);
    sorted.push(obj);
  }

  objects.forEach((o) => visit(o));
  return sorted;
}

/**
 * Generate full Urwigo-compatible Lua script for the cartridge
 */
export function generateCartridgeLuaScript(cart: Cartridge): string {
  let sb = '';
  sb += '-- Urwigo-style cartridge generated by jourwigo CartridgeCompiler\n';
  sb += 'Cartridge = Wherigo.ZCartridge()\n';
  sb += `Cartridge.Name = "${escapeLua(cart.name)}"\n`;
  sb += `Cartridge.Description = "${escapeLua(cart.description)}"\n`;
  sb += 'Cartridge.Activity = "TourGuide"\n';
  sb += 'Cartridge.StartingLocationDescription = "Start"\n';
  sb += `Cartridge.StartingLocation = Wherigo.ZonePoint(${cart.latitude || 0}, ${cart.longitude || 0}, ${cart.altitude || 0})\n`;
  sb += `Cartridge.Version = "${escapeLua(cart.version)}"\n`;
  sb += `Cartridge.Author = "${escapeLua(cart.author)}"\n\n`;

  sb += '-- Constructed Persistent Objects & Inventories\n';
  const sortedObjs = getSortedObjects(cart.objects);
  sortedObjs.forEach((obj) => {
    sb += `${obj.varName} = ${obj.constructor || '{}'}\n`;
    obj.props.forEach((p) => {
      if (p.k) {
        sb += `${obj.varName}.${p.k} = ${formatPropertyValue(p.v, p.t)}\n`;
      }
    });
    sb += '\n';
  });

  sb += 'function OnStart()\n';
  sb += `    Wherigo.MessageBox({Text = "Welcome to ${escapeLua(cart.name)}!"})\n`;
  sb += 'end\n';

  return sb;
}

/**
 * Compile/Package cartridge into a valid .gwc binary file conforming to the openwig/Wherigo specification
 */
export function compileCartridgeToGwcBytes(cart: Cartridge): Uint8Array {
  const luaScript = generateCartridgeLuaScript(cart);
  const scriptBytes = new TextEncoder().encode(luaScript);

  // 1. Build Header Bytes
  const headerParts: Uint8Array[] = [];

  function appendDoubleLE(val: number) {
    const buf = new ArrayBuffer(8);
    new DataView(buf).setFloat64(0, val, true);
    headerParts.push(new Uint8Array(buf));
  }

  function appendShortLE(val: number) {
    const buf = new ArrayBuffer(2);
    new DataView(buf).setInt16(0, val, true);
    headerParts.push(new Uint8Array(buf));
  }

  function appendIntLE(val: number) {
    const buf = new ArrayBuffer(4);
    new DataView(buf).setInt32(0, val, true);
    headerParts.push(new Uint8Array(buf));
  }

  function appendNullString(str: string) {
    const encoded = new TextEncoder().encode(str || '');
    const out = new Uint8Array(encoded.length + 1);
    out.set(encoded);
    out[encoded.length] = 0;
    headerParts.push(out);
  }

  function appendBytes(bytes: number[]) {
    headerParts.push(new Uint8Array(bytes));
  }

  appendDoubleLE(cart.latitude || 0);
  appendDoubleLE(cart.longitude || 0);
  appendBytes(new Array(8).fill(0));
  appendBytes(new Array(8).fill(0));
  appendShortLE(0);
  appendShortLE(0);
  appendNullString('Wherigo');
  appendNullString('JourwigoPlayer');
  appendBytes(new Array(8).fill(0));
  appendNullString(cart.name);
  appendNullString('12345678-1234-1234-1234-123456789012');
  appendNullString(cart.description);
  appendNullString('Start description');
  appendNullString(cart.version);
  appendNullString(cart.author);
  appendNullString('https://github.com/JakeDot/jourwigo');
  appendNullString('MIDP-2.0/CLDC-1.1');
  appendBytes(new Array(4).fill(0));
  appendNullString('123456');

  // Concatenate header bytes
  const totalHeaderLen = headerParts.reduce((acc, p) => acc + p.length, 0);
  const headerBytes = new Uint8Array(totalHeaderLen);
  let hOffset = 0;
  for (const part of headerParts) {
    headerBytes.set(part, hOffset);
    hOffset += part.length;
  }

  const headerPos = 15;
  const bytecodeOffset = headerPos + 4 + headerBytes.length;

  // Build the complete GWC container
  const containerParts: Uint8Array[] = [];

  // Magic bytes: 0x02, 0x0a, 0x43, 0x41, 0x52, 0x54, 0x00 ('\x02\nCART\0')
  containerParts.push(new Uint8Array([0x02, 0x0a, 0x43, 0x41, 0x52, 0x54, 0x00]));

  // Media count (1), reserved (0), bytecodeOffset
  const offBuf = new ArrayBuffer(8);
  const offView = new DataView(offBuf);
  offView.setInt16(0, 1, true);
  offView.setInt16(2, 0, true);
  offView.setInt32(4, bytecodeOffset, true);
  containerParts.push(new Uint8Array(offBuf));

  // Header length & header bytes
  const hLenBuf = new ArrayBuffer(4);
  new DataView(hLenBuf).setInt32(0, headerBytes.length, true);
  containerParts.push(new Uint8Array(hLenBuf));
  containerParts.push(headerBytes);

  // Bytecode length & bytecode
  const sLenBuf = new ArrayBuffer(4);
  new DataView(sLenBuf).setInt32(0, scriptBytes.length, true);
  containerParts.push(new Uint8Array(sLenBuf));
  containerParts.push(scriptBytes);

  // Combine all parts
  const totalGwcLen = containerParts.reduce((acc, p) => acc + p.length, 0);
  const gwcBytes = new Uint8Array(totalGwcLen);
  let gOffset = 0;
  for (const part of containerParts) {
    gwcBytes.set(part, gOffset);
    gOffset += part.length;
  }

  return gwcBytes;
}

export function downloadFile(content: Uint8Array | string, filename: string, mimeType: string) {
  const blob = typeof content === 'string'
    ? new Blob([content], { type: mimeType })
    : new Blob([content.buffer as ArrayBuffer], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Parse an imported .gwc or .lua file to extract cartridge details and objects
 */
export async function parseCartridgeFile(file: File): Promise<Partial<Cartridge>> {
  const name = file.name.replace(/\.[^/.]+$/, '');
  if (file.name.endsWith('.lua')) {
    const text = await file.text();
    return parseLuaCartridge(text, name);
  }

  if (file.name.endsWith('.gwc')) {
    const buffer = await file.arrayBuffer();
    return parseGwcBytes(new Uint8Array(buffer), name);
  }

  return { name };
}

function parseLuaCartridge(lua: string, defaultName: string): Partial<Cartridge> {
  const cart: Partial<Cartridge> = {
    name: defaultName,
    author: 'Author',
    version: '1.0',
    description: '',
    latitude: 0,
    longitude: 0,
    altitude: 0,
    objects: [],
  };

  const nameMatch = lua.match(/Cartridge\.Name\s*=\s*"([^"]+)"/);
  if (nameMatch) cart.name = nameMatch[1];

  const authorMatch = lua.match(/Cartridge\.Author\s*=\s*"([^"]+)"/);
  if (authorMatch) cart.author = authorMatch[1];

  const verMatch = lua.match(/Cartridge\.Version\s*=\s*"([^"]+)"/);
  if (verMatch) cart.version = verMatch[1];

  const descMatch = lua.match(/Cartridge\.Description\s*=\s*"([^"]+)"/);
  if (descMatch) cart.description = descMatch[1];

  const locMatch = lua.match(/Cartridge\.StartingLocation\s*=\s*Wherigo\.ZonePoint\s*\(\s*([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*\)/);
  if (locMatch) {
    cart.latitude = parseFloat(locMatch[1]) || 0;
    cart.longitude = parseFloat(locMatch[2]) || 0;
    cart.altitude = parseFloat(locMatch[3]) || 0;
  }

  return cart;
}

function parseGwcBytes(bytes: Uint8Array, defaultName: string): Partial<Cartridge> {
  // Check magic 0x02, 0x0a, 0x43, 0x41, 0x52, 0x54, 0x00
  if (bytes.length < 32 || bytes[0] !== 0x02 || bytes[2] !== 0x43) {
    return { name: defaultName };
  }

  try {
    const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
    // Header length is at offset 15
    const headerLen = view.getInt32(15, true);
    let offset = 19;
    const lat = view.getFloat64(offset, true);
    const lon = view.getFloat64(offset + 8, true);
    offset += 16 + 16 + 4; // skip doubles and shorts

    // Read null-terminated strings
    function readNullStr(): string {
      let str = '';
      while (offset < bytes.length && bytes[offset] !== 0) {
        str += String.fromCharCode(bytes[offset]);
        offset++;
      }
      offset++; // skip null
      return str;
    }

    readNullStr(); // Wherigo
    readNullStr(); // Device
    offset += 8; // skip reserved
    const cartName = readNullStr() || defaultName;
    readNullStr(); // UUID
    const desc = readNullStr();
    readNullStr(); // start desc
    const version = readNullStr();
    const author = readNullStr();

    return {
      name: cartName,
      author: author || 'Author',
      version: version || '1.0',
      description: desc || '',
      latitude: isNaN(lat) ? 0 : lat,
      longitude: isNaN(lon) ? 0 : lon,
      altitude: 0,
      objects: [],
    };
  } catch (err) {
    console.warn('GWC parse error:', err);
    return { name: defaultName };
  }
}
